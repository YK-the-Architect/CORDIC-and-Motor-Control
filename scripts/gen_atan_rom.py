#!/usr/bin/env python3
"""Generate rtl/atan_rom.sv: the CORDIC angle table as integer constants.

The old atan_rom computed the table with $atan and real math inside a
constant function, which synthesis tools may not accept. This script does
the real math once and writes plain integers into the RTL instead.

Each angle atan(2^-i) is stored as a fraction of a full turn with 48 bits
(2^48 = 360 degrees). atan_rom rounds it to the angle width it is built
with (ANGLE_BITS), using integer math only.

Run from the repo root:  python3 scripts/gen_atan_rom.py
"""
import math
from pathlib import Path

MASTER = 48   # bits per full turn in the stored constants
N_MAX = 32    # table entries; ITER can be at most this

vals = [round(math.atan(2.0 ** -i) / (2 * math.pi) * 2 ** MASTER) for i in range(N_MAX)]

cases = "\n".join(
    f"      {i:2d}: atan_turns = {MASTER}'d{v};   // atan(2^-{i}) = {math.degrees(math.atan(2.0 ** -i)):.10f} deg"
    for i, v in enumerate(vals)
)

sv = f"""// Generated by scripts/gen_atan_rom.py. Do not edit by hand; rerun the script.
//
// atan(2^-i) in binary angle units, for i = 0 to ITER - 1:
//   atan_out[i] = round(atan(2^-i) / 360 deg * 2^ANGLE_BITS)
// The constants are stored with {MASTER} bits per full turn and rounded to
// ANGLE_BITS here with integer math only, so the table synthesizes.
module atan_rom #(
  parameter int WIDTH      = 16,     // width of each entry (the z lane width)
  parameter int ITER       = 16,
  parameter int ANGLE_BITS = WIDTH   // 2^ANGLE_BITS = 360 degrees
)(
  output logic [WIDTH-1:0] atan_out [ITER]
);

  localparam int MASTER = {MASTER};

  // atan(2^-i) with 2^{MASTER} = 360 degrees
  function automatic logic [MASTER-1:0] atan_turns(input int i);
    case (i)
{cases}
      default: atan_turns = '0;
    endcase
  endfunction

  // round to ANGLE_BITS: add half an output LSB, then drop the extra bits
  function automatic logic [WIDTH-1:0] atan_entry(input int i);
    logic [MASTER:0] v;
    v = {{1'b0, atan_turns(i)}} + ((MASTER+1)'(1) << (MASTER - ANGLE_BITS - 1));
    return WIDTH'(v >> (MASTER - ANGLE_BITS));
  endfunction

  for (genvar i = 0; i < ITER; i++) begin : g_entry
    assign atan_out[i] = atan_entry(i);
  end

  // elaboration-time checks
  initial begin
    if (ITER > {N_MAX}) $error("atan_rom: ITER = %0d, the table has {N_MAX} entries", ITER);
    if (ANGLE_BITS >= MASTER) $error("atan_rom: ANGLE_BITS must be below %0d", MASTER);
  end

endmodule
"""

out = Path(__file__).resolve().parent.parent / "rtl" / "atan_rom.sv"
out.write_text(sv)
print(f"wrote {out} ({N_MAX} entries, {MASTER} bits per turn)")
