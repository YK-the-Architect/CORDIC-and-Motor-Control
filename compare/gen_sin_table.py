#!/usr/bin/env python3
"""compare/gen_sin_table.py : writes compare/sin_table.sv, the quarter-wave sine table used by
mult_rot.sv (the multiplier-based rotation we compare CORDIC with).

  T[k] = round(sin(k * 90 deg / 2^TB) * 2^SC), k = 0 .. 2^TB      (entry 2^TB is 1.0)
  D[k] = T[k + 1] - T[k], D[2^TB] = 0                             (slope for interpolation)

  python3 compare/gen_sin_table.py [TB] [SC]     defaults: TB = 7 (128 intervals), SC = 17
"""
import math, os, sys

TB = int(sys.argv[1]) if len(sys.argv) > 1 else 7
SC = int(sys.argv[2]) if len(sys.argv) > 2 else 17
M = 1 << TB
T = [round(math.sin(k * math.pi / 2 / M) * (1 << SC)) for k in range(M + 1)]
D = [T[k + 1] - T[k] for k in range(M)] + [0]
TW = (1 << SC).bit_length() + 1            # T holds 0 .. 2^SC, unsigned
DW = max(D).bit_length()

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "sin_table.sv")
with open(out, "w") as f:
    f.write("// Generated by compare/gen_sin_table.py. Do not edit by hand; rerun the script.\n")
    f.write(f"// Quarter-wave sine: TB = {TB} ({M} intervals), SC = {SC} fraction bits.\n")
    f.write(f"//   sin_t(k) = round(sin(k * 90 deg / {M}) * 2^{SC}),  sin_d(k) = sin_t(k + 1) - sin_t(k)\n")
    f.write("package sin_table;\n")
    f.write(f"  localparam int TB = {TB}, SC = {SC}, TW = {TW}, DW = {DW};\n")
    f.write(f"  function automatic logic [TW - 1 : 0] sin_t(input logic [TB : 0] k);\n    case (k)\n")
    for k, v in enumerate(T):
        f.write(f"      {k}: sin_t = {TW}'d{v};\n")
    f.write("      default: sin_t = '0;\n    endcase\n  endfunction\n")
    f.write(f"  function automatic logic [DW - 1 : 0] sin_d(input logic [TB : 0] k);\n    case (k)\n")
    for k, v in enumerate(D):
        f.write(f"      {k}: sin_d = {DW}'d{v};\n")
    f.write("      default: sin_d = '0;\n    endcase\n  endfunction\n")
    f.write("endpackage\n")
print(f"wrote {out}: {M + 1} entries, T {TW} bits, D {DW} bits")
